import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import ts from 'typescript';

// Native widget resources are generated projections, not a second design/i18n authority.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mobile = path.join(root, 'apps/mobile');
const native = path.join(mobile, 'modules/cindy-quota-widget');
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(mobile, 'src/theme/tokens.ts'), 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
}).outputText, { exports });
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(mobile, 'src/theme/quotaWidgetTokens.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports });
const { lightColors, darkColors, spacing, radius, typeScale, quotaWidgetTokens } = exports;
const roles = ['surfaceElevated', 'textPrimary', 'textSecondary', 'border'];
const languages = ['en', 'zh-CN', 'zh-TW', 'ja', 'ko'];
const translations = Object.fromEntries(languages.map(language => [language,
  JSON.parse(fs.readFileSync(path.join(mobile, `src/i18n/locales/${language}/settings.json`), 'utf8')).quotaWidget,
]));
const snake = value => value.replace(/[A-Z]/g, v => '_' + v.toLowerCase());
const xml = value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const androidText = value => xml(value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"'));
const swift = value => JSON.stringify(value).replace(/\\u([0-9a-f]{4})/gi, '\\u{$1}');
const dictionary = obj => '[' + Object.entries(obj).map(([k, v]) => `${swift(k)}: ${swift(v)}`).join(',\n    ') + ']';
const generated = new Map();
generated.set('widget/QuotaWidgetResources.swift', `// Generated by scripts/generate-quota-widget-resources.mjs. Do not edit.
import SwiftUI

enum QuotaWidgetResources {
  static let frameInset: CGFloat = ${quotaWidgetTokens.inset}
  static let ringSize: CGFloat = ${quotaWidgetTokens.ring}
  static let ringStroke: CGFloat = ${quotaWidgetTokens.stroke}
  static let brandSize: CGFloat = ${quotaWidgetTokens.brandSize}
  static let detailSize: CGFloat = ${quotaWidgetTokens.detailSize}
${Object.entries(quotaWidgetTokens.medium).map(([key, value]) => `  static let medium${key[0].toUpperCase() + key.slice(1)}: CGFloat = ${value}`).join("\n")}
  static let footnote: CGFloat = ${typeScale.footnote}
  static let caption: CGFloat = ${typeScale.caption}
  static let micro: CGFloat = ${typeScale.micro}
  static let gap: CGFloat = ${spacing.xs}
  static let padding: CGFloat = ${spacing.md}
  private static let strings: [String: [String: String]] = [
    ${Object.entries(translations).map(([k, v]) => `${swift(k)}: ${dictionary(v)}`).join(',\n    ')}
  ]
  static func text(_ key: String, locale: String) -> String {
    let tag = locale.lowercased().replacingOccurrences(of: "_", with: "-")
    let language = tag.hasPrefix("zh") ? (tag.contains("hant") || tag.contains("tw") || tag.contains("hk") ? "zh-TW" : "zh-CN") : String(tag.prefix(2))
    return strings[language]?[key] ?? strings["en"]?[key] ?? ""
  }
  static func color(_ role: String, dark: Bool) -> Color {
    let palette = dark ? ${dictionary({ ...Object.fromEntries(roles.map(role => [role, darkColors[role]])), ...quotaWidgetTokens.dark })} : ${dictionary({ ...Object.fromEntries(roles.map(role => [role, lightColors[role]])), ...quotaWidgetTokens.light })}
    let hex = palette[role] ?? palette["textPrimary"]!
    let value = UInt32(hex.dropFirst(), radix: 16)!
    return Color(.sRGB, red: Double((value >> 16) & 255) / 255, green: Double((value >> 8) & 255) / 255, blue: Double(value & 255) / 255, opacity: 1)
  }
}
`);
const resourceDir = 'android/src/main/res';
const xmlHeader = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from Mobile tokens / settings translations. Do not edit. -->\n';
const localeDir = { en: 'values', 'zh-CN': 'values-zh-rCN', 'zh-TW': 'values-zh-rTW', ja: 'values-ja', ko: 'values-ko' };
for (const [language, values] of Object.entries(translations)) {
  generated.set(`${resourceDir}/${localeDir[language]}/cindy_quota_strings.xml`, xmlHeader + '<resources>\n' +
    Object.entries(values).map(([key, value]) => `  <string name="cindy_widget_${snake(key)}" formatted="false">${androidText(value)}</string>`).join('\n') + '\n</resources>\n');
}
for (const [mode, palette] of Object.entries({ light: lightColors, dark: darkColors })) {
  generated.set(`${resourceDir}/values${mode === 'dark' ? '-night' : ''}/cindy_quota_colors.xml`, xmlHeader + '<resources>\n' +
    roles.map(role => `  <color name="cindy_widget_${snake(role)}">${palette[role]}</color>`).join('\n') + '\n</resources>\n');
  // Fixed-mode drawables let RemoteViews respect the in-app appearance preference too.
  generated.set(`${resourceDir}/drawable/cindy_quota_background_${mode}.xml`, xmlHeader +
    `<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n  <solid android:color="${palette.surfaceElevated}" />\n  <stroke android:width="1dp" android:color="${palette.border}" />\n  <corners android:radius="${radius.container}dp" />\n</shape>\n`);
}
generated.set(`${resourceDir}/values/cindy_quota_dimensions.xml`, xmlHeader + '<resources>\n' +
  Object.entries({ padding: `${spacing.md}dp`, radius: `${radius.container}dp`, footnote: `${typeScale.footnote}sp`, caption: `${typeScale.caption}sp`, micro: `${typeScale.micro}sp` })
    .map(([name, value]) => `  <dimen name="cindy_widget_${name}">${value}</dimen>`).join('\n') + '\n</resources>\n');
let mismatch = false;
for (const [relative, content] of generated) {
  const target = path.join(native, relative);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) { console.error(`Stale widget resource: ${relative}`); mismatch = true; }
  } else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
}
if (mismatch) process.exitCode = 1;
